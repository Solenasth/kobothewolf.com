// `npm run gen`: writes the standalone validators (see standalone.ts).
import { mkdirSync, writeFileSync } from 'node:fs';
import { generate } from './standalone.ts';

const OUT = 'src/core/generated';

mkdirSync(OUT, { recursive: true });
writeFileSync(`${OUT}/validators.js`, generate());
writeFileSync(
  `${OUT}/validators.d.ts`,
  `// Generated by scripts/gen-validators.ts. Do not edit.
export interface ValidationError { instancePath: string; message?: string }
export interface Validator { (data: unknown): boolean; errors?: ValidationError[] | null }
export const validateDocument: Validator;
`,
);
console.log(`gen-validators: wrote ${OUT}/validators.js`);
