// Page themes (FR-P10, DESIGN §6): each style's temas.json, checked, and turned
// into CSS. Values are tokens.json color names or hex colors. No DOM.

/** The page tokens a theme may set, with today's values (src/theme/ui.css). */
export const DEFAULT_TOKENS = {
  'ui-bg': '#F6F1F7',
  'ui-panel': '#FFFFFF',
  'ui-line': '#E4D9E7',
  'ui-text': '#2B2233',
  'ui-muted': '#6B5B73',
  'ui-focus': '#E0559B',
  'ui-accent-text': '#BF3A7E',
  chicle: '#FF8FB8',
  rosa: '#FFC8DD',
  algodon: '#FFE4EE',
  blanco: '#FFFFFF',
  azul: '#BDE0FE',
} as const;
export type Token = keyof typeof DEFAULT_TOKENS;
/** Tokens a theme may override; text and panel colors stay. */
export const THEME_TOKENS: readonly Token[] = ['ui-bg', 'ui-line', 'ui-muted', 'ui-focus', 'ui-accent-text', 'chicle', 'rosa', 'algodon'];
export const BACKGROUNDS = ['liso', 'cuaderno', 'crema', 'femboy'] as const;
export type Background = (typeof BACKGROUNDS)[number];

export interface ThemeFile {
  porDefecto: string;
  temas: { id: string; fondo: string; colores: Record<string, string> }[];
}

export interface Theme {
  id: string;
  fondo: Background;
  /** Every page token, after the theme's overrides. */
  tokens: Record<Token, string>;
  /** The colors the page background shows, for contrast checks. */
  pattern: string[];
}

const HEX = /^#[0-9A-Fa-f]{6}$/;

/** Checks a temas.json against the style's colors; returns the themes or the problems. */
export function readThemes(file: ThemeFile, colors: Record<string, string>): { ok: true; themes: Theme[]; byDefault: string } | { ok: false; problems: string[] } {
  const problems: string[] = [];
  const ids = new Set<string>();
  const themes: Theme[] = [];
  for (const t of file.temas) {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(t.id)) problems.push(`theme "${t.id}": the id must be a lowercase slug`);
    if (ids.has(t.id)) problems.push(`theme "${t.id}" is listed twice`);
    ids.add(t.id);
    if (!(BACKGROUNDS as readonly string[]).includes(t.fondo)) problems.push(`theme "${t.id}": background "${t.fondo}" isn't one of ${BACKGROUNDS.join(', ')}`);
    const tokens: Record<Token, string> = { ...DEFAULT_TOKENS };
    for (const [name, value] of Object.entries(t.colores)) {
      if (!(THEME_TOKENS as readonly string[]).includes(name)) {
        problems.push(`theme "${t.id}": "${name}" isn't a token a theme may set (${THEME_TOKENS.join(', ')})`);
        continue;
      }
      const hex = HEX.test(value) ? value : colors[value];
      if (!hex || !HEX.test(hex)) problems.push(`theme "${t.id}": ${name} = "${value}" is neither a hex color nor a color in tokens.json`);
      else tokens[name as Token] = hex.toUpperCase();
    }
    const fondo = t.fondo as Background;
    const pattern = fondo === 'cuaderno' ? [tokens['ui-bg'], tokens['ui-line']] : fondo === 'femboy' ? [...FEMBOY] : [tokens['ui-bg']];
    themes.push({ id: t.id, fondo, tokens, pattern });
  }
  if (!ids.has(file.porDefecto)) problems.push(`the default theme "${file.porDefecto}" isn't listed`);
  return problems.length ? { ok: false, problems } : { ok: true, themes, byDefault: file.porDefecto };
}

/** The femboy stripes keep the palette's own pink, white and blue, whatever a theme sets. */
const FEMBOY = [DEFAULT_TOKENS.algodon, DEFAULT_TOKENS.blanco, DEFAULT_TOKENS.azul] as const;

const BODY: Record<Background, string> = {
  liso: 'background: var(--ui-bg);',
  crema: 'background: var(--ui-bg);',
  cuaderno:
    'background-color: var(--ui-bg); background-image: linear-gradient(var(--ui-line) 1px, transparent 1px), linear-gradient(90deg, var(--ui-line) 1px, transparent 1px); background-size: 26px 26px;',
  femboy: `background: repeating-linear-gradient(-35deg, ${FEMBOY[0]} 0 40px, ${FEMBOY[1]} 40px 80px, ${FEMBOY[2]} 80px 120px, ${FEMBOY[1]} 120px 160px);`,
};

/** The CSS for every theme but the default, which is the page's own :root. */
export function themesCss(themes: readonly Theme[], byDefault: string): string {
  const blocks = themes
    .filter((t) => t.id !== byDefault)
    .map((t) => {
      const sel = `:root[data-theme="${t.id}"]`;
      const vars = THEME_TOKENS.map((k) => `--${k}: ${t.tokens[k]};`).join(' ');
      const patterned = t.fondo === 'cuaderno' || t.fondo === 'femboy';
      return [
        `${sel} { ${vars} }`,
        `${sel} body { ${BODY[t.fondo]} }`,
        // Text never sits on a pattern: the editor gets a solid panel.
        ...(patterned ? [`${sel} .editor { background: var(--ui-bg); border: 2px solid var(--ui-line); border-radius: 20px; padding: 20px; }`] : []),
      ].join('\n');
    });
  return `/* Generated by scripts/gen-themes.ts from styles/<style>/temas.json (FR-P10). Do not edit. */\n${blocks.join('\n\n')}\n`;
}

/** WCAG relative luminance and contrast ratio. */
export function contrast(a: string, b: string): number {
  const lum = (hex: string) => {
    const [r, g, bl] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
    return 0.2126 * r! + 0.7152 * g! + 0.0722 * bl!;
  };
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi! + 0.05) / (lo! + 0.05);
}
