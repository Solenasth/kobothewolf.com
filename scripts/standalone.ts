// Compiles the document schema into a standalone ES module (DESIGN §11), so the
// browser validates untrusted .kobo.json files without shipping ajv.
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createAjv, interop, schemaId } from './schemas.ts';

// ajv's only runtime helper: string length in code points.
const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
const LOCAL_UCS2 = '((s) => { let n = 0; for (const _ of s) n++; return n; })';

export function generate(): string {
  const ajv = createAjv({ standalone: true });
  let code = interop(standaloneCode)(ajv, { validateDocument: schemaId('document') });
  code = code.split(UCS2).join(LOCAL_UCS2);
  const leftovers = code.match(/\brequire\(|^\s*import\s/m);
  if (leftovers) throw new Error(`gen-validators: unexpected runtime import in generated code (${leftovers[0]})`);
  return `// Generated by scripts/gen-validators.ts from schemas/. Do not edit.\n${code}`;
}
